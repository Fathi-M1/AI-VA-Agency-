// Builds supabase/sql-editor/ — the four files the owner pastes into the Supabase SQL editor,
// in order — from supabase/migrations and supabase/checks. Run after changing a migration:
//   node scripts/build-sql-editor.mjs
// tests/db/sql-editor.db.test.ts fails if the files are stale, and runs them end to end.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const SUPABASE = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase")
const MIGRATIONS = join(SUPABASE, "migrations")
const OUT = join(SUPABASE, "sql-editor")

const BACKUP = `-- STEP 1 of 4 — BACKUP (paste into Supabase → SQL Editor → New query → Run)
-- Copies every table in the app (schema "public") into a private schema "backup_phase0",
-- inside your database. Changes nothing else. The API can't reach this schema.
-- Run it ONCE: if it says "schema backup_phase0 already exists", a backup is already there; go on to step 2.
-- What you should see: a list of tables with their row counts (the same numbers step 2 shows).

create schema backup_phase0;
revoke all on schema backup_phase0 from public;

do $$
declare
  t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public' order by tablename loop
    execute format('create table backup_phase0.%I as table public.%I', t, t);
  end loop;
end $$;

select 'businesses' as backed_up, count(*) as rows from backup_phase0.businesses
union all select 'contacts (customers)', count(*) from backup_phase0.contacts
union all select 'conversations', count(*) from backup_phase0.conversations
union all select 'messages', count(*) from backup_phase0.messages
union all select 'bookings', count(*) from backup_phase0.bookings
union all select 'escalations (needs you)', count(*) from backup_phase0.escalations;
`

const BEFORE_HEADER = `-- STEP 2 of 4 — BEFORE-CHECK (read-only; paste into a new query → Run)
-- What you should see: six "count" rows, and NO "blocker" rows. Write the six numbers down.
-- Any "blocker" row → STOP and send it to Claude (a value the migrations don't know).

`

const AFTER_HEADER = `-- STEP 4 of 4 — AFTER-CHECK (read-only; paste into a new query → Run)
-- What you should see: the six "count" rows show the SAME numbers as step 2;
-- every "check" row says "ok" (11 rows); "Cruz business" says "requests, Asia/Manila".
-- Anything else → send Claude the whole result.

`

function migrateFile() {
  const files = readdirSync(MIGRATIONS).filter((f) => /^\d{14}_.+\.sql$/.test(f)).sort()
  const last = files.at(-1).slice(0, 14)
  const parts = files.map((f) => `-- ===== ${f}\n\n${readFileSync(join(MIGRATIONS, f), "utf8").trim()}\n`)
  const versions = files.map((f) => `  ('${f.slice(0, 14)}', '${f.slice(15, -4)}')`).join(",\n")
  return `-- STEP 3 of 4 — APPLY THE MIGRATIONS (paste into a new query → Run). This changes the database.
-- All ${files.length} migrations run in ONE transaction: if anything fails, NOTHING is changed.
-- It refuses to run before the backup (step 1), and refuses to run twice.
-- It records each migration in Supabase's migration history (supabase_migrations.schema_migrations).
-- What you should see: "Success. No rows returned".
-- An error → nothing was changed. Copy the whole error and send it to Claude. Don't run it again.
-- Generated by scripts/build-sql-editor.mjs from supabase/migrations — don't edit by hand.

begin;

do $$
declare
  applied boolean := false;
begin
  -- (dynamic: the history table doesn't exist yet on a first run)
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select exists (select 1 from supabase_migrations.schema_migrations where version = $1)' into applied using '${last}';
  end if;
  if applied then
    raise exception 'These migrations are already applied. Nothing was changed.';
  end if;
  if not exists (select 1 from pg_namespace where nspname = 'backup_phase0') then
    raise exception 'Run 1-backup.sql first. Nothing was changed.';
  end if;
end $$;

${parts.join("\n")}
-- ===== migration history (what the Supabase CLI records)

create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);
insert into supabase_migrations.schema_migrations (version, name) values
${versions}
on conflict (version) do nothing;

commit;
`
}

/** { fileName: content } for supabase/sql-editor/. */
export function buildFiles() {
  return {
    "1-backup.sql": BACKUP,
    "2-before-check.sql": BEFORE_HEADER + readFileSync(join(SUPABASE, "checks", "before-migration.sql"), "utf8"),
    "3-migrate.sql": migrateFile(),
    "4-after-check.sql": AFTER_HEADER + readFileSync(join(SUPABASE, "checks", "after-migration.sql"), "utf8"),
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(OUT, { recursive: true })
  for (const [name, content] of Object.entries(buildFiles())) writeFileSync(join(OUT, name), content)
  console.log(`wrote ${Object.keys(buildFiles()).length} files to supabase/sql-editor/`)
}
